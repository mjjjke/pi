	/** Build a detached compaction candidate without changing memory or the journal. */
	buildCompactionEntry<T = unknown>(
		summary: string,
		firstKeptEntryId: string | null,
		tokensBefore: number,
		details?: T,
		fromHook?: boolean,
		usage?: Usage,
		options?: { carry?: "desired" | "delivered"; boundary?: string },
	): CompactionEntry<T> {
		const timestamp = new Date().toISOString();
		const systemMessage = getCurrentSystemMessage(this.buildSessionProjection().messages);
		const standing = this._buildStandingCarry(options?.carry ?? "delivered", new Date(timestamp).getTime());
		const id = generateId(this.byId);
		const entry: CompactionEntry<T> = {
			type: "compaction",
			id,
			parentId: this.leafId,
			timestamp,
			summary,
			firstKeptEntryId: firstKeptEntryId ?? id,
			tokensBefore,
			details,
			usage,
			fromHook,
			...(systemMessage
				? { systemMessage: { ...structuredClone(systemMessage), timestamp: new Date(timestamp).getTime() } }
				: {}),
			standing,
			boundary: options?.boundary ?? COMPACTION_BOUNDARY_TEXT_V1,
		};
		return entry;
	}

	/** Commit exactly the previewed candidate, or build one for an ordinary blocking compaction. */
	appendCompaction<T = unknown>(candidate: CompactionEntry<T>): string;
	appendCompaction<T = unknown>(
		summary: string,
		firstKeptEntryId: string | null,
		tokensBefore: number,
		details?: T,
		fromHook?: boolean,
		usage?: Usage,
		options?: { carry?: "desired" | "delivered" },
	): string;
	appendCompaction<T = unknown>(
		summaryOrCandidate: string | CompactionEntry<T>,
		firstKeptEntryId?: string | null,
		tokensBefore?: number,
		details?: T,
		fromHook?: boolean,
		usage?: Usage,
		options?: { carry?: "desired" | "delivered" },
	): string {
		const entry =
			typeof summaryOrCandidate === "string"
				? this.buildCompactionEntry(
						summaryOrCandidate,
						firstKeptEntryId ?? null,
						tokensBefore ?? 0,
						details,
						fromHook,
						usage,
						options,
					)
				: summaryOrCandidate;
		if (entry.parentId !== this.leafId || this.byId.has(entry.id)) {
			throw new Error("stale compaction candidate");
		}
		this._appendEntry(entry);
		return entry.id;
	}

	/**
	 * Standing values in effect for the next request, in key order (§7.4): `desired` between runs (a pending
	 * value counts as delivered), `delivered` mid-run (a pending value stays pending). Cleared keys carry nothing.
	 */
	private _buildStandingCarry(carry: "desired" | "delivered", timestamp: number): CompactionStandingItem[] {
		const items: CompactionStandingItem[] = [];
		for (const state of getStandingState(this.getBranch())) {
			if (!state.desired) continue;
			const content = carry === "desired" ? state.desired.content : state.delivered?.content;
			if (content === undefined) continue;
			items.push({
				key: state.key,
				message: deepFreeze({ role: "developer", content: structuredClone(content), timestamp }),
			});
		}
		return items;
	}

	/** Append the desired value of a standing instruction (non-context state entry); undefined content clears it. */
	appendStandingInstruction(
		key: string,
		content: StandingInstructionContent | undefined,
		apply?: StandingInstructionApply,
	): string {
		if (!key) throw new Error("Standing instruction key must not be empty");
		const entry: StandingInstructionEntry = {
			type: "standing_instruction",
			id: generateId(this.byId),
			parentId: this.leafId,
			timestamp: new Date().toISOString(),
			key,
			...(content !== undefined ? { content: structuredClone(content) } : {}),
			...(content !== undefined && apply ? { apply } : {}),
		};
		this._appendEntry(entry);
		return entry.id;
	}

	/** Derived standing-instruction state of the active branch (§7.2). */
	getStandingState(): StandingInstructionState[] {
		return getStandingState(this.getBranch());
	}

	/** Append a custom entry (for extensions) as child of current leaf, then advance leaf. Returns entry id. */
	appendCustomEntry(customType: string, data?: unknown): string {
		const entry: CustomEntry = {
			type: "custom",
			customType,
			data,
			id: generateId(this.byId),
			parentId: this.leafId,
			timestamp: new Date().toISOString(),
		};
		this._appendEntry(entry);
		return entry.id;
	}

	/** Append a session info entry (e.g., display name). Returns entry id. */
	appendSessionInfo(name: string): string {
		const sanitizedName = name.replace(/[\r\n]+/g, " ").trim();
		const entry: SessionInfoEntry = {
			type: "session_info",
			id: generateId(this.byId),
			parentId: this.leafId,
			timestamp: new Date().toISOString(),
			name: sanitizedName,
		};
		this._appendEntry(entry);
		return entry.id;
	}

	/** Get the current session name from the latest session_info entry, if any. */
	getSessionName(): string | undefined {
		// Walk entries in reverse to find the latest session_info entry.
		// Empty names explicitly clear the session title. Reads fileEntries directly: the footer
		// calls this on every frame, and getEntries() copies the whole session.
		for (let i = this.fileEntries.length - 1; i >= 0; i--) {
			const entry = this.fileEntries[i];
			if (entry.type === "session_info") {
				return entry.name?.trim() || undefined;
			}
		}
		return undefined;
	}

	/**
	 * Append a custom message entry (for extensions) that participates in LLM context.
	 * @param customType Extension identifier for filtering on reload
	 * @param content Message content (string or TextContent/ImageContent array)
	 * @param display Whether to show in TUI (true = styled display, false = hidden)
	 * @param details Optional extension-specific metadata (not sent to LLM)
	 * @returns Entry id
	 */
	appendCustomMessageEntry<T = unknown>(
		customType: string,
		content: string | (TextContent | ImageContent)[],
		display: boolean,
		details?: T,
	): string {
		const entry: CustomMessageEntry<T> = {
			type: "custom_message",
			customType,
			content,
			display,
			details,
			id: generateId(this.byId),
			parentId: this.leafId,
			timestamp: new Date().toISOString(),
		};
		this._appendEntry(entry);
		return entry.id;
	}

	/** Append a branch-local edit to an earlier model-visible entry. */
	appendContextEdit(targetId: string, replacement: ContextEditEntry["replacement"]): string {
		if (
			replacement !== null &&
			(typeof replacement !== "object" ||
				!("content" in replacement) ||
				(typeof replacement.content !== "string" && !Array.isArray(replacement.content)))
		) {
			throw new Error("Context edit replacement must be null or contain string/array content");
		}
		const target = this.byId.get(targetId);
		if (!target) throw new Error(`Entry ${targetId} not found`);
		if (!this.getBranch().some((entry) => entry.id === targetId)) {
			throw new Error(`Entry ${targetId} is not on the active branch`);
		}
		const editable =
			target.type === "custom_message" ||
			(target.type === "message" &&
				(target.message.role === "user" ||
					target.message.role === "assistant" ||
					target.message.role === "toolResult"));
		if (!editable) throw new Error(`Entry ${targetId} does not contribute editable model content`);
		const targetRole = target.type === "message" ? target.message.role : "custom";
		const normalizedReplacement =
			replacement !== null &&
			(targetRole === "assistant" || targetRole === "toolResult") &&
			typeof replacement.content === "string"
				? { content: [{ type: "text" as const, text: replacement.content }] }
				: replacement;
		const entry: ContextEditEntry = {
			type: "context_edit",
			id: generateId(this.byId),
			parentId: this.leafId,
			timestamp: new Date().toISOString(),
			targetId,
			replacement: normalizedReplacement,
		};
		this._appendEntry(entry);
		return entry.id;
	}

